import json

with open('tinless system model.ipynb', encoding='utf-8') as f:
    nb = json.load(f)

# ── Updated TinlessSimulation class (adds snap support) ───────────────────────
class_src = [
    "class TinlessSimulation:\n",
    "    \"\"\"\n",
    "    Transient model: graphite annulus radiating to a central cylindrical powerstick.\n",
    "    Each timestep reads inner wall temps, computes radiation + electricity, and updates\n",
    "    the block temperature distribution via StorageModule.update_temps.\n",
    "    \"\"\"\n",
    "\n",
    "    def __init__(self, storage, powerstick, T_sur=300, block_heat_loss=False):\n",
    "        self.storage         = storage\n",
    "        self.powerstick      = powerstick\n",
    "        self.T_sur           = T_sur\n",
    "        self.block_heat_loss = block_heat_loss\n",
    "\n",
    "        # Geometry derived from objects (constant throughout sim)\n",
    "        r_ps_eff      = 2 * powerstick.width / np.pi   # equiv. cylinder radius = 2*side_len/pi\n",
    "        self.VF       = r_ps_eff / storage.block.rad_in\n",
    "        self.A_ps_seg = powerstick.A_step               # 4*side_len*seg_len = cylindrical equiv.\n",
    "\n",
    "    def _step_calc(self, T_dist):\n",
    "        ps   = self.powerstick\n",
    "        n_ax = self.storage.num_ax_segments\n",
    "        Q_rad   = np.zeros(n_ax)\n",
    "        P_elec  = np.zeros(n_ax)\n",
    "        Q_waste = np.zeros(n_ax)\n",
    "        for i in range(n_ax):\n",
    "            T_wall_i = T_dist[i, 0]\n",
    "            Q_rad[i] = spectral_net_radiation(\n",
    "                T_wall_i, ps.emissivity_table, self.VF,\n",
    "                self.A_ps_seg, ps.f_bare, ps.f_active, ps.liner_bool\n",
    "            )\n",
    "            P_elec[i], Q_waste[i] = ps.generate_electricity_step(\n",
    "                T_wall_i, self.VF, ps.panel_efficiency\n",
    "            )\n",
    "        return Q_rad, P_elec, Q_waste\n",
    "\n",
    "    def run_simulation(self, end_time, dt, sub_steps, snap_every=None, print_interval=0):\n",
    "        \"\"\"\n",
    "        Parameters\n",
    "        ----------\n",
    "        end_time       : float  Total simulation time [s]\n",
    "        dt             : float  Time step [s]\n",
    "        sub_steps      : int    FD sub-steps per time step (stability)\n",
    "        snap_every     : float  Save full temp distribution every this many seconds\n",
    "                                (None = save only initial and final)\n",
    "        print_interval : int    Print progress every N steps (0 = silent)\n",
    "\n",
    "        Returns\n",
    "        -------\n",
    "        dict: time-series arrays + temp_snapshots (shape: n_snaps x num_ax x num_rad)\n",
    "        \"\"\"\n",
    "        storage = self.storage\n",
    "        n_steps = int(end_time / dt)\n",
    "        snap_steps = max(1, round(snap_every / dt)) if snap_every else n_steps\n",
    "\n",
    "        time_arr    = np.zeros(n_steps + 1)\n",
    "        Q_arr       = np.zeros(n_steps + 1)\n",
    "        P_elec_arr  = np.zeros(n_steps + 1)\n",
    "        T_avg_arr   = np.zeros(n_steps + 1)\n",
    "        T_inner_arr = np.zeros(n_steps + 1)\n",
    "        T_outer_arr = np.zeros(n_steps + 1)\n",
    "        snap_times  = []\n",
    "        temp_snaps  = []\n",
    "\n",
    "        # t = 0 snapshot\n",
    "        T = storage.block.temp_dist\n",
    "        Q0, P0, _ = self._step_calc(T)\n",
    "        Q_arr[0]       = Q0.sum()\n",
    "        P_elec_arr[0]  = P0.sum()\n",
    "        T_avg_arr[0]   = T.mean()\n",
    "        T_inner_arr[0] = T[:, 0].mean()\n",
    "        T_outer_arr[0] = T[:, -1].mean()\n",
    "        snap_times.append(0.0)\n",
    "        temp_snaps.append(T.copy())\n",
    "\n",
    "        for step in range(n_steps):\n",
    "            T = storage.block.temp_dist\n",
    "            Q_rad, P_elec, Q_waste = self._step_calc(T)\n",
    "\n",
    "            T_new, _, _ = storage.update_temps(\n",
    "                T, -Q_rad, dt, sub_steps, self.T_sur, self.block_heat_loss\n",
    "            )\n",
    "            storage.block.temp_dist = T_new\n",
    "\n",
    "            idx = step + 1\n",
    "            time_arr[idx]    = idx * dt\n",
    "            Q_arr[idx]       = Q_rad.sum()\n",
    "            P_elec_arr[idx]  = P_elec.sum()\n",
    "            T_avg_arr[idx]   = T_new.mean()\n",
    "            T_inner_arr[idx] = T_new[:, 0].mean()\n",
    "            T_outer_arr[idx] = T_new[:, -1].mean()\n",
    "\n",
    "            if idx % snap_steps == 0:\n",
    "                snap_times.append(time_arr[idx])\n",
    "                temp_snaps.append(T_new.copy())\n",
    "\n",
    "            if print_interval and (idx % print_interval == 0):\n",
    "                print(f\"t = {time_arr[idx]/3600:.2f} hr  \"\n",
    "                      f\"T_avg = {T_avg_arr[idx]:.0f} K  \"\n",
    "                      f\"Q = {Q_arr[idx]/1e3:.1f} kW  \"\n",
    "                      f\"P = {P_elec_arr[idx]/1e3:.1f} kW\")\n",
    "\n",
    "        # Always include final state\n",
    "        if snap_times[-1] != time_arr[-1]:\n",
    "            snap_times.append(time_arr[-1])\n",
    "            temp_snaps.append(storage.block.temp_dist.copy())\n",
    "\n",
    "        return {\n",
    "            'time':           time_arr,\n",
    "            'Q_rad':          Q_arr,\n",
    "            'P_elec':         P_elec_arr,\n",
    "            'T_avg':          T_avg_arr,\n",
    "            'T_inner':        T_inner_arr,\n",
    "            'T_outer':        T_outer_arr,\n",
    "            'snap_times':     np.array(snap_times),\n",
    "            'temp_snapshots': np.array(temp_snaps),  # shape: (n_snaps, num_ax, num_rad)\n",
    "        }\n",
]

# ── Setup + run cell ──────────────────────────────────────────────────────────
run_src = [
    "# ── Load inputs ───────────────────────────────────────────────────────────────\n",
    "with open('tinless_model_input.yaml') as f:\n",
    "    cfg = yaml.safe_load(f)\n",
    "\n",
    "end_time             = cfg['end_time']\n",
    "dt                   = cfg['dt']\n",
    "sub_steps            = cfg['sub_steps']\n",
    "T_sur                = cfg['T_sur']\n",
    "liner_bool           = cfg['liner_bool']\n",
    "block_heat_loss_bool = cfg['block_heat_loss_bool']\n",
    "\n",
    "# Emissivity table — parse first range entry (extend here for time-varying tables)\n",
    "raw_emis = cfg['emissivity_tables'][0]['value']\n",
    "emissivity_table = [(tuple(row[0]), float(row[1]), float(row[2]), float(row[3]))\n",
    "                     for row in raw_emis]\n",
    "\n",
    "# ── Storage block geometry ────────────────────────────────────────────────────\n",
    "s = cfg['storage']\n",
    "avg_power        = s['avg_power']\n",
    "duration_hr      = s['duration_hr']\n",
    "T_min            = s['T_min']\n",
    "block_temp_range = s['block_temp_range']\n",
    "L                = s['L']\n",
    "th_ins           = s['th_ins']\n",
    "num_ax           = s['num_ax_segments']\n",
    "num_rad          = s['num_rad_segments']\n",
    "\n",
    "T_max   = T_min + block_temp_range\n",
    "T_init  = T_max\n",
    "T_avg_  = T_min + block_temp_range / 2\n",
    "E_req   = avg_power * duration_hr * 3600\n",
    "e_dens  = storage_rho(T_avg_) * storage_cp(T_avg_) * block_temp_range\n",
    "V_block = E_req / e_dens\n",
    "\n",
    "# ── Powerstick geometry ───────────────────────────────────────────────────────\n",
    "p = cfg['powerstick']\n",
    "side_len       = p['side_len']\n",
    "area_ratio     = p['area_ratio']\n",
    "panel_eff      = p['panel_efficiency']\n",
    "f_bare         = p['f_bare']\n",
    "f_active       = p['f_active']\n",
    "T_ps           = p['cooling_temp']\n",
    "\n",
    "r_ps_eff = 2 * side_len / np.pi\n",
    "r_in     = r_ps_eff * area_ratio\n",
    "r_out    = np.sqrt(V_block / (np.pi * L) + r_in**2)\n",
    "\n",
    'print(f"Block: r_in={r_in:.3f} m  r_out={r_out:.3f} m  L={L} m  V={V_block:.2f} m^3")\n',
    'print(f"VF = r_ps_eff/r_in = {r_ps_eff/r_in:.4f}  |  T_init = {T_init} K")\n',
    "\n",
    "# ── Build components ──────────────────────────────────────────────────────────\n",
    "initial_temp_dist = np.full((num_ax, num_rad), float(T_init))\n",
    "block = GraphiteBlock(\n",
    "    initial_temp_distribution=initial_temp_dist,\n",
    "    inner_radius=r_in, outer_radius=r_out, length=L, th_ins=th_ins,\n",
    ")\n",
    "dummy_pipe = Pipe(OD=0.02, length=L, wall_thickness=0.001, roughness=1e-5, th_ins=0.0)\n",
    "storage = StorageModule(\n",
    "    N_pipes=1, Pipe=dummy_pipe, Block=block,\n",
    "    num_ax_segments=num_ax, num_rad_segments=num_rad, bypass_range=[0, 1],\n",
    ")\n",
    "powerstick = PowerStick(\n",
    "    axial_steps=num_ax, width=side_len, height=L,\n",
    "    cooling_temp=T_ps, panel_efficiency=panel_eff,\n",
    "    f_bare=f_bare, f_active=f_active,\n",
    "    liner_bool=liner_bool, emissivity_table=emissivity_table,\n",
    ")\n",
    "\n",
    "# ── Run ───────────────────────────────────────────────────────────────────────\n",
    "sim = TinlessSimulation(storage, powerstick, T_sur=T_sur, block_heat_loss=block_heat_loss_bool)\n",
    "\n",
    "results = sim.run_simulation(\n",
    "    end_time      = end_time,\n",
    "    dt            = dt,\n",
    "    sub_steps     = sub_steps,\n",
    "    snap_every    = 3600,       # save full temp distribution every 1 hr\n",
    "    print_interval = int(3600 / dt),  # print progress every 1 hr of sim time\n",
    ")\n",
    "\n",
    "# ── Save ──────────────────────────────────────────────────────────────────────\n",
    "np.savez_compressed(\n",
    "    'tinless_results.npz',\n",
    "    time           = results['time'],\n",
    "    Q_rad          = results['Q_rad'],\n",
    "    P_elec         = results['P_elec'],\n",
    "    T_avg          = results['T_avg'],\n",
    "    T_inner        = results['T_inner'],\n",
    "    T_outer        = results['T_outer'],\n",
    "    snap_times     = results['snap_times'],\n",
    "    temp_snapshots = results['temp_snapshots'],\n",
    ")\n",
    'print(f"\\nSaved {len(results[\'snap_times\'])} temp snapshots, "\n',
    '      f"{len(results[\'time\'])} time steps  ->  tinless_results.npz")\n',
]

# Update class cell
for cell in nb['cells']:
    if cell.get('id', '').startswith('03dd9a23'):
        cell['source'] = class_src
        cell['outputs'] = []
        cell['execution_count'] = None
        print(f'Updated class cell 03dd9a23')

# Add run cell at end
run_cell = {
    'cell_type': 'code',
    'execution_count': None,
    'id': 'b2e4f810',
    'metadata': {},
    'outputs': [],
    'source': run_src,
}
nb['cells'].append(run_cell)
print(f'Appended run cell. Total cells: {len(nb["cells"])}')

with open('tinless system model.ipynb', 'w', encoding='utf-8') as f:
    json.dump(nb, f, indent=1, ensure_ascii=False)
print('Done.')
