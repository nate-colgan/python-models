import json

with open('tinless system model.ipynb', encoding='utf-8') as f:
    nb = json.load(f)

src = [
    "class TinlessSimulation:\n",
    "    \"\"\"\n",
    "    Transient model: graphite annulus radiating to a central cylindrical powerstick.\n",
    "    Each timestep reads inner wall temps, computes radiation + electricity, and updates\n",
    "    the block temperature distribution via StorageModule.update_temps.\n",
    "    \"\"\"\n",
    "\n",
    "    def __init__(self, storage, powerstick, T_sur=300, block_heat_loss=False):\n",
    "        self.storage     = storage\n",
    "        self.powerstick  = powerstick\n",
    "        self.T_sur       = T_sur\n",
    "        self.block_heat_loss = block_heat_loss\n",
    "\n",
    "        # Geometry derived from objects (set once; doesn't change during sim)\n",
    "        r_ps_eff  = 2 * powerstick.width / np.pi   # equiv. cylinder radius = 2*side_len/pi\n",
    "        self.VF       = r_ps_eff / storage.block.rad_in\n",
    "        self.A_ps_seg = powerstick.A_step           # 4*side_len*seg_len = cylindrical equiv.\n",
    "\n",
    "    def _step_calc(self, T_dist):\n",
    "        \"\"\"Compute Q_rad and P_elec for every axial segment given current temp distribution.\"\"\"\n",
    "        ps    = self.powerstick\n",
    "        n_ax  = self.storage.num_ax_segments\n",
    "        Q_rad   = np.zeros(n_ax)\n",
    "        P_elec  = np.zeros(n_ax)\n",
    "        Q_waste = np.zeros(n_ax)\n",
    "        for i in range(n_ax):\n",
    "            T_wall_i = T_dist[i, 0]\n",
    "            Q_rad[i] = spectral_net_radiation(\n",
    "                T_wall_i, ps.emissivity_table, self.VF,\n",
    "                self.A_ps_seg, ps.f_bare, ps.f_active, ps.liner_bool\n",
    "            )\n",
    "            P_elec[i], Q_waste[i] = ps.generate_electricity_step(\n",
    "                T_wall_i, self.VF, ps.panel_efficiency\n",
    "            )\n",
    "        return Q_rad, P_elec, Q_waste\n",
    "\n",
    "    def run_simulation(self, end_time, dt, sub_steps, print_interval=0):\n",
    "        \"\"\"\n",
    "        Run transient simulation.\n",
    "\n",
    "        Parameters\n",
    "        ----------\n",
    "        end_time       : float  Total simulation time [s]\n",
    "        dt             : float  Time step [s]\n",
    "        sub_steps      : int    FD sub-steps per time step (stability)\n",
    "        print_interval : int    Print progress every N steps (0 = silent)\n",
    "\n",
    "        Returns\n",
    "        -------\n",
    "        dict with arrays: time, Q_rad, P_elec, T_avg, T_inner, T_outer\n",
    "        \"\"\"\n",
    "        storage = self.storage\n",
    "        n_steps = int(end_time / dt)\n",
    "\n",
    "        time_arr    = np.zeros(n_steps + 1)\n",
    "        Q_arr       = np.zeros(n_steps + 1)\n",
    "        P_elec_arr  = np.zeros(n_steps + 1)\n",
    "        T_avg_arr   = np.zeros(n_steps + 1)\n",
    "        T_inner_arr = np.zeros(n_steps + 1)\n",
    "        T_outer_arr = np.zeros(n_steps + 1)\n",
    "\n",
    "        # Record initial state\n",
    "        T = storage.block.temp_dist\n",
    "        Q0, P0, _ = self._step_calc(T)\n",
    "        Q_arr[0]       = Q0.sum()\n",
    "        P_elec_arr[0]  = P0.sum()\n",
    "        T_avg_arr[0]   = T.mean()\n",
    "        T_inner_arr[0] = T[:, 0].mean()\n",
    "        T_outer_arr[0] = T[:, -1].mean()\n",
    "\n",
    "        for step in range(n_steps):\n",
    "            T = storage.block.temp_dist\n",
    "            Q_rad, P_elec, Q_waste = self._step_calc(T)\n",
    "\n",
    "            # Heat leaves the inner wall -> pass -Q_rad to update_temps\n",
    "            T_new, _, _ = storage.update_temps(\n",
    "                T, -Q_rad, dt, sub_steps, self.T_sur, self.block_heat_loss\n",
    "            )\n",
    "            storage.block.temp_dist = T_new\n",
    "\n",
    "            idx = step + 1\n",
    "            time_arr[idx]    = idx * dt\n",
    "            Q_arr[idx]       = Q_rad.sum()\n",
    "            P_elec_arr[idx]  = P_elec.sum()\n",
    "            T_avg_arr[idx]   = T_new.mean()\n",
    "            T_inner_arr[idx] = T_new[:, 0].mean()\n",
    "            T_outer_arr[idx] = T_new[:, -1].mean()\n",
    "\n",
    "            if print_interval and (idx % print_interval == 0):\n",
    "                print(f\"t = {time_arr[idx]/3600:.2f} hr  \"\n",
    "                      f\"T_avg = {T_avg_arr[idx]:.0f} K  \"\n",
    "                      f\"Q = {Q_arr[idx]/1e3:.1f} kW  \"\n",
    "                      f\"P = {P_elec_arr[idx]/1e3:.1f} kW\")\n",
    "\n",
    "        return {\n",
    "            'time':    time_arr,\n",
    "            'Q_rad':   Q_arr,\n",
    "            'P_elec':  P_elec_arr,\n",
    "            'T_avg':   T_avg_arr,\n",
    "            'T_inner': T_inner_arr,\n",
    "            'T_outer': T_outer_arr,\n",
    "        }\n",
]

# Replace the empty cell (03dd9a23)
for cell in nb['cells']:
    if cell.get('id', '').startswith('03dd9a23'):
        cell['source'] = src
        cell['outputs'] = []
        cell['execution_count'] = None
        print(f'Replaced cell {cell["id"][:8]}')
        break

with open('tinless system model.ipynb', 'w', encoding='utf-8') as f:
    json.dump(nb, f, indent=1, ensure_ascii=False)
print('Done.')
