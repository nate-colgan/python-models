# ── Sweep cell (ff640d4b) ─────────────────────────────────────────────────────
sweep_src = (
    "import thermal.components as _tc\n"
    "from scipy.integrate import cumulative_trapezoid\n"
    "\n"
    "# ── Fixed design parameters ──────────────────────────────────────────────\n"
    "_avg_flux        = 15          # W/cm^2\n"
    "_duration_hr     = 20          # hr  (fixed discharge duration)\n"
    "_side_len        = 0.13        # m\n"
    "_L               = 3.0         # m\n"
    "_th_ins          = 0.0         # m\n"
    "_num_ax          = 6\n"
    "_num_rad         = 12\n"
    "_T_ps            = 323         # K\n"
    "_panel_eff       = 0.5\n"
    "_f_bare          = 0.2\n"
    "_f_active        = 0.83\n"
    "_liner_bool      = False\n"
    "_T_sur            = 300         # K\n"
    "_dt              = 1200        # s\n"
    "_sub_steps       = 5\n"
    "_pwr_tol         = 0.01        # bisection tolerance (fraction of avg_power)\n"
    "\n"
    "_r_ps_eff      = 2 * _side_len / np.pi\n"
    "_avg_power_tot = _avg_flux * 4 * _side_len * _L * 1e4   # total thermal [W]\n"
    "_avg_power     = _avg_power_tot * (1 - _f_bare) * _f_active  # cell-weighted [W]\n"
    "\n"
    "# ── Sweep parameters ─────────────────────────────────────────────────────\n"
    "temp_range_vals = [250, 500]          # K  (block operating temperature swing)\n"
    "T_max_vals      = [2273, 2373, 2673]  # K  (block full/initial temperature)\n"
    "bandgap_vals    = [1.24, 1.38, 1.55]  # microns\n"
    "\n"
    "# ── Helpers ───────────────────────────────────────────────────────────────\n"
    "def _build_and_run(T_max, dT_range, area_ratio, emis_table):\n"
    '    """\n'
    "    Size a graphite storage block and run a full transient discharge simulation.\n"
    "\n"
    "    Block volume is sized from the required energy: V_block = avg_power_tot *\n"
    "    duration / volumetric_energy_density, where energy density is evaluated at\n"
    "    the mid-point temperature.  Inner radius follows from area_ratio = r_in /\n"
    "    r_ps_eff; outer radius is derived from V_block and r_in.\n"
    "\n"
    "    Inputs\n"
    "    ------\n"
    "    T_max       : float -- block initial (full) temperature [K]\n"
    "    dT_range    : float -- operating temperature swing (T_max - T_min) [K]\n"
    "    area_ratio  : float -- r_in / r_ps_eff (sets view factor VF = 1/area_ratio)\n"
    "    emis_table  : list  -- spectral emissivity table for PowerStick;\n"
    "                           each entry: ((wl_lo, wl_hi), emis_active, emis_bare,\n"
    "                           emis_inactive)\n"
    "\n"
    "    Returns\n"
    "    -------\n"
    "    res_   : dict  -- simulation results from TinlessSimulation.run_simulation\n"
    "    r_out_ : float -- computed block outer radius [m]\n"
    '    """\n'
    "    T_min_    = T_max - dT_range\n"
    "    T_avg_mid = T_min_ + dT_range / 2\n"
    "    e_dens_   = storage_rho(T_avg_mid) * storage_cp(T_avg_mid) * dT_range\n"
    "    V_blk_    = _avg_power_tot * _duration_hr * 3600 / e_dens_\n"
    "    r_in_     = _r_ps_eff * area_ratio\n"
    "    r_out_    = np.sqrt(V_blk_ / (np.pi * _L) + r_in_**2)\n"
    "\n"
    "    init_dist_ = np.full((_num_ax, _num_rad), float(T_max))\n"
    "    block_  = GraphiteBlock(init_dist_, inner_radius=r_in_, outer_radius=r_out_,\n"
    "                            length=_L, th_ins=_th_ins)\n"
    "    pipe_   = Pipe(OD=0.02, length=_L, wall_thickness=0.001, roughness=1e-5, th_ins=0.0)\n"
    "    stor_   = StorageModule(N_pipes=1, Pipe=pipe_, Block=block_,\n"
    "                            num_ax_segments=_num_ax, num_rad_segments=_num_rad,\n"
    "                            bypass_range=[0, 1])\n"
    "    ps_     = PowerStick(axial_steps=_num_ax, width=_side_len, height=_L,\n"
    "                         cooling_temp=_T_ps, panel_efficiency=_panel_eff,\n"
    "                         f_bare=_f_bare, f_active=_f_active,\n"
    "                         liner_bool=_liner_bool, emissivity_table=emis_table)\n"
    "    sim_    = TinlessSimulation(stor_, ps_, T_sur=_T_sur, block_heat_loss=False)\n"
    "    res_    = sim_.run_simulation(end_time=_duration_hr * 3600, dt=_dt, sub_steps=_sub_steps)\n"
    "    return res_, r_out_\n"
    "\n"
    "def _pss_avg_q(res_, dT_range, T_max):\n"
    '    """\n'
    "    Compute average cell heat flux over the pseudo-steady-state (PSS) window.\n"
    "\n"
    "    PSS onset = argmin(T_inner - T_avg): point of maximum radial gradient.\n"
    "    Window ends when SOC = (T_avg - T_min) / dT_range drops to zero.\n"
    "    Q_cell (cell-area-weighted flux) is averaged, not Q_rad.\n"
    "\n"
    "    Inputs\n"
    "    ------\n"
    "    res_     : dict  -- results from _build_and_run\n"
    "    dT_range : float -- operating temperature swing [K]\n"
    "    T_max    : float -- block initial temperature [K]\n"
    "\n"
    "    Returns\n"
    "    -------\n"
    "    float -- mean Q_cell [W] from PSS onset to SOC=0\n"
    '    """\n'
    "    delta    = res_['T_inner'] - res_['T_avg']\n"
    "    T_min_   = T_max - dT_range\n"
    "    soc      = (res_['T_avg'] - T_min_) / dT_range\n"
    "    idx_pss  = int(np.argmin(delta))\n"
    "    soc0     = np.where(soc <= 0)[0]\n"
    "    idx_soc0 = int(soc0[0]) if len(soc0) else len(soc) - 1\n"
    "    if idx_pss >= idx_soc0:\n"
    "        return float(res_['Q_cell'][idx_pss])\n"
    "    return float(res_['Q_cell'][idx_pss:idx_soc0 + 1].mean())\n"
    "\n"
    "# ── Main sweep ───────────────────────────────────────────────────────────\n"
    "sweep_results = {}\n"
    "total = len(temp_range_vals) * len(T_max_vals) * len(bandgap_vals)\n"
    "n = 0\n"
    "\n"
    "for bg_val in bandgap_vals:\n"
    "    emis_table_bg = [\n"
    "        ((0.1,    bg_val), 0.9,  0.1, 0.1),\n"
    "        ((bg_val, 20.0),   0.05, 0.1, 0.1),\n"
    "    ]\n"
    "\n"
    "    for dT_range in temp_range_vals:\n"
    "        for T_max in T_max_vals:\n"
    "            n += 1\n"
    "            print(f'[{n}/{total}] T_max={T_max}K  dT={dT_range}K  bg={bg_val}um  -- bisecting area_ratio')\n"
    "\n"
    "            def _f(ar, _Tmax=T_max, _dT=dT_range, _emis=emis_table_bg):\n"
    "                res_, _ = _build_and_run(_Tmax, _dT, ar, _emis)\n"
    "                q = _pss_avg_q(res_, _dT, _Tmax)\n"
    "                print(f'    ar={ar:.3f}  avg_Q={q/1e3:.1f} kW  (target {_avg_power/1e3:.0f} kW)')\n"
    "                return q - _avg_power\n"
    "\n"
    "            f0 = _f(10.0)\n"
    "            if abs(f0) / _avg_power <= _pwr_tol:\n"
    "                ar_opt = 10.0\n"
    "            else:\n"
    "                if f0 > 0:\n"
    "                    ar_hi, f_hi = 10.0, f0\n"
    "                    ar_lo = 10.0\n"
    "                    while True:\n"
    "                        ar_lo /= 2\n"
    "                        f_lo = _f(ar_lo)\n"
    "                        if f_lo <= 0:\n"
    "                            break\n"
    "                        ar_hi, f_hi = ar_lo, f_lo\n"
    "                else:\n"
    "                    ar_lo, f_lo = 10.0, f0\n"
    "                    ar_hi = 10.0\n"
    "                    while True:\n"
    "                        ar_hi *= 2\n"
    "                        f_hi = _f(ar_hi)\n"
    "                        if f_hi >= 0:\n"
    "                            break\n"
    "                        ar_lo, f_lo = ar_hi, f_hi\n"
    "\n"
    "                for _ in range(20):\n"
    "                    ar_mid = (ar_lo + ar_hi) / 2\n"
    "                    f_mid  = _f(ar_mid)\n"
    "                    if abs(f_mid) / _avg_power <= _pwr_tol:\n"
    "                        break\n"
    "                    if f_mid > 0:\n"
    "                        ar_hi = ar_mid\n"
    "                    else:\n"
    "                        ar_lo = ar_mid\n"
    "                ar_opt = (ar_lo + ar_hi) / 2\n"
    "\n"
    "            res_opt, r_out_opt = _build_and_run(T_max, dT_range, ar_opt, emis_table_bg)\n"
    "            Q  = res_opt['Q_rad']\n"
    "            Pe = res_opt['P_elec']\n"
    "            Ti = res_opt['T_inner']\n"
    "            Ta = res_opt['T_avg']\n"
    "            t  = res_opt['time']\n"
    "            cum_Q = cumulative_trapezoid(Q,  t, initial=0)\n"
    "            cum_P = cumulative_trapezoid(Pe, t, initial=0)\n"
    "            eff   = cum_P[-1] / cum_Q[-1] * 100 if cum_Q[-1] > 0 else 0.0\n"
    "\n"
    "            sweep_results[(dT_range, T_max, bg_val)] = dict(\n"
    "                area_ratio = ar_opt,\n"
    "                r_out      = r_out_opt,\n"
    "                peak_dT    = float(np.max(Ta - Ti)),\n"
    "                peak_power = float(np.max(Q)) / 1e3,\n"
    "                efficiency = eff,\n"
    "            )\n"
    "            print(f'    -> ar_opt={ar_opt:.3f}  r_out={r_out_opt:.3f}m  '\n"
    "                  f'peak_Q={np.max(Q)/1e3:.0f}kW  eff={eff:.1f}%')\n"
    "\n"
    "print('Sweep complete.')\n"
)

